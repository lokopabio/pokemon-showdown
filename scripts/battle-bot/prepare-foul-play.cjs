'use strict';
// Imports species data only. Does not claim ability/move parity or launch a bot.
const fs = require('node:fs');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const {Dex} = require('../../dist/sim');
const ENGINE = 'f7b147f13637ceecc1b0d1e9172ec232af4d45d0';
const FOUL = '8f541f80f91f960603673796559f796b10ccf0fb';
const norm = s => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');
function speciesData() {
  const dex = Dex.forFormat('gen7ou');
  const all = dex.species.all();
  const first = all.findIndex(s => s.id === 'carletto'), last = all.findIndex(s => s.id === 'lugamon');
  if (first < 0 || last < first) throw new Error('Missing species boundaries');
  const pool = all.slice(first, last + 1).filter(s => s.exists && s.num < 0 && !s.isMega && !s.battleOnly && !s.requiredItem);
  const names = {hp: 'hp', atk: 'attack', def: 'defense', spa: 'special-attack', spd: 'special-defense', spe: 'speed'};
  const data = {};
  for (const s of pool) {
    data[s.id] = {num: s.num, name: s.id, types: s.types.map(t => t.toLowerCase()),
      baseStats: Object.fromEntries(Object.entries(names).map(([k,v]) => [v, s.baseStats[k]])),
      abilities: s.abilities, weightkg: s.weightkg, heightm: s.heightm,
      ...(s.evos?.length ? {evos: s.evos} : {}), ...(s.prevo ? {prevo: s.prevo} : {}),
      // No otherFormes/requiredItem: Mega Evolutions are excluded from this integration.
      ...(s.gender ? {gender: s.gender} : {genderRatio: s.genderRatio}),
    };
  }
  return {dex, pool, data};
}
function prepare(engineDir, foulDir) {
  engineDir = path.resolve(engineDir); foulDir = path.resolve(foulDir);
  for (const [dir, expected] of [[engineDir, ENGINE], [foulDir, FOUL]]) {
    const actual = execFileSync('git', ['rev-parse', 'HEAD'], {cwd: dir, encoding: 'utf8'}).trim();
    if (actual !== expected) throw new Error(`Unsupported upstream revision in ${dir}: ${actual}; expected ${expected}`);
  }
  const {pool, data} = speciesData();
  const writes = new Map();
  const read = (root, file) => fs.readFileSync(path.join(root, file), 'utf8');
  let species = read(engineDir, 'src/pokemon.rs');
  const enumMarker = '        // ROMAN FAKEMON BEGIN';
  species = species.replace(/        \/\/ ROMAN FAKEMON BEGIN[\s\S]*?        \/\/ ROMAN FAKEMON END\n/g, '');
  const end = '    },\n    default = NONE';
  if (!species.includes(end)) throw new Error('Pokemon enum structure changed');
  species = species.replace(end, enumMarker + '\n' + pool.map(s => `        ${s.id.toUpperCase()},`).join('\n') + '\n        // ROMAN FAKEMON END\n' + end);
  writes.set(path.join(engineDir, 'src/pokemon.rs'), species);
  let stats = read(engineDir, 'src/genx/base_stats.rs');
  stats = stats.replace(/            \/\/ ROMAN STATS BEGIN[\s\S]*?            \/\/ ROMAN STATS END\n/g, '');
  const marker = '    pub fn base_stats(&self) -> (i16, i16, i16, i16, i16, i16) {\n        match self {\n';
  if (!stats.includes(marker)) throw new Error('Base stat structure changed');
  stats = stats.replace(marker, marker + '            // ROMAN STATS BEGIN\n' + pool.map(s => `            PokemonName::${s.id.toUpperCase()} => (${['hp','atk','def','spa','spd','spe'].map(k => s.baseStats[k]).join(', ')}),`).join('\n') + '\n            // ROMAN STATS END\n');
  writes.set(path.join(engineDir, 'src/genx/base_stats.rs'), stats);
  let state = read(engineDir, 'src/genx/state.rs');
  // Gen 7: a Shadow Tag user cannot be trapped by another Shadow Tag user.
  const oldTrap = '} else if opponent_active.ability == Abilities::SHADOWTAG {\n            return true;';
  const newTrap = '} else if opponent_active.ability == Abilities::SHADOWTAG {\n            return active_pkmn.ability != Abilities::SHADOWTAG;';
  if (!state.includes(oldTrap) && !state.includes(newTrap)) throw new Error('Shadow Tag implementation changed');
  state = state.replace(oldTrap, newTrap);
  writes.set(path.join(engineDir, 'src/genx/state.rs'), state);
  const pokedex = JSON.parse(read(foulDir, 'fp/data/pokedex.json'));
  Object.assign(pokedex, data);
  writes.set(path.join(foulDir, 'fp/data/pokedex.json'), JSON.stringify(pokedex, null, 4) + '\n');
  const guard = `# Generated by prepare-foul-play.cjs. Own teams only, not opponent reveals.\nimport re\nALLOWED = frozenset(${JSON.stringify(pool.map(s => s.id))})\ndef validate_custom_team(team):\n    if len(team) != 6:\n        raise ValueError('Expected six Fakemon')\n    for member in team:\n        species = re.sub(r'[^a-z0-9]', '', (member.get('species') or member.get('name') or '').lower())\n        if species not in ALLOWED:\n            raise ValueError('Species outside Carletto-Lugamon: ' + species)\n        if re.sub(r'[^a-z0-9]', '', member.get('ability', '').lower()) == 'moody':\n            raise ValueError('Moody is excluded from bot teams')\n        item = re.sub(r'[^a-z0-9]', '', member.get('item', '').lower())\n        if item in ${JSON.stringify(Dex.items.all().filter(i => i.zMove || i.zMoveType || i.megaStone).map(i => i.id))}:\n            raise ValueError('Z-Crystals and Mega Stones are disabled')\n`;
  writes.set(path.join(foulDir, 'fp/teams/roman_guard.py'), guard);
  let loader = read(foulDir, 'fp/teams/load_team.py');
  if (!loader.includes('from .roman_guard import validate_custom_team')) {
    const anchor = '    return (\n        export_to_packed(team_export),';
    if (!loader.includes(anchor)) throw new Error('Team loader structure changed');
    loader = 'from .roman_guard import validate_custom_team\n' + loader.replace(anchor, '    validate_custom_team(export_to_dict(team_export))\n' + anchor);
    loader = loader.replace('        return "null", "", ""', '        raise ValueError("An explicit Fakemon team is required")');
  }
  writes.set(path.join(foulDir, 'fp/teams/load_team.py'), loader);
  // Native tests prove identifiers roundtrip and every exported stat tuple matches.
  const rustTest = `use poke_engine::pokemon::PokemonName;\nuse std::str::FromStr;\n#[test]\nfn roman_species_roundtrip_and_stats() {\n${pool.map(s => `    let p = PokemonName::from_str("${s.id}").unwrap();\n    assert_eq!(p.to_string().to_lowercase(), "${s.id}");\n    assert_eq!(p.base_stats(), (${['hp','atk','def','spa','spd','spe'].map(k => s.baseStats[k]).join(', ')}));`).join('\n')}\n}\n`;
  writes.set(path.join(engineDir, 'tests/roman_species.rs'), rustTest);
  writes.set(path.join(engineDir, 'tests/roman_shadow_tag.rs'), `use poke_engine::state::{State, PokemonType};
use poke_engine::engine::abilities::Abilities;
use poke_engine::engine::items::Items;
#[test]
fn shadow_tag_trapping_and_exemptions() {
    let mut state = State::default();
    state.side_two.get_active().ability = Abilities::SHADOWTAG;
    state.side_one.get_active().ability = Abilities::BLAZE;
    state.side_one.get_active().item = Items::NONE;
    state.side_one.get_active().types = (PokemonType::NORMAL, PokemonType::TYPELESS);
    assert!(state.side_one.trapped(state.side_two.get_active_immutable()));
    state.side_one.get_active().ability = Abilities::SHADOWTAG;
    assert!(!state.side_one.trapped(state.side_two.get_active_immutable()));
    state.side_one.get_active().ability = Abilities::BLAZE;
    state.side_one.get_active().types = (PokemonType::GHOST, PokemonType::TYPELESS);
    assert!(!state.side_one.trapped(state.side_two.get_active_immutable()));
    state.side_one.get_active().types = (PokemonType::NORMAL, PokemonType::TYPELESS);
    state.side_one.get_active().item = Items::SHEDSHELL;
    assert!(!state.side_one.trapped(state.side_two.get_active_immutable()));
}
`);
  // Validate every transformation before writing any file.
  for (const [file, content] of writes) fs.writeFileSync(file, content);
  const report = {schema: 1, upstream: {engine: ENGINE, foulPlay: FOUL}, speciesCount: pool.length,
    selectableSpecies: pool.map(s => s.id), megaEvolutions: false, zMoves: false, excludedOwnAbilities: ['moody'], shadowTagAllowed: true,
    readyForBattle: false, pending: ['Compile and run Rust tests', 'Modified ability/move parity', 'Custom opponent-set inference', 'End-to-end benchmark'],
    imported: ['Species identifiers', 'Base stats', 'Types', 'Weight', 'Abilities metadata', 'Own-team species/item guard']};
  fs.writeFileSync(path.join(foulDir, 'roman-import.json'), JSON.stringify(report, null, 2) + '\n');
  return report;
}
if (require.main === module) {
  const [engine, foul] = process.argv.slice(2);
  if (!engine || !foul) throw new Error('Usage: node scripts/battle-bot/prepare-foul-play.cjs POKE_ENGINE_DIR FOUL_PLAY_DIR');
  console.log(JSON.stringify(prepare(engine, foul), null, 2));
}
module.exports = {prepare, speciesData, ENGINE, FOUL};
